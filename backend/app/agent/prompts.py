def build_planner_user(question: str) -> str:
    """User-промпт планировщика (§5.1): подставляет вопрос.

    str.replace, а не .format — в PLANNER_PROMPT литеральные фигурные скобки JSON-схемы.
    """
    return PLANNER_PROMPT.replace("{question}", question)


def build_synth_user(question: str, citations_block: str, context_block: str) -> str:
    """User-промпт синтеза (§5.3): вопрос + список CITATIONS + сериализованные данные.

    str.replace, а не .format — в SYNTH_PROMPT литеральные фигурные скобки §5.3-таблицы.
    """
    return (
        SYNTH_PROMPT
        .replace("{question}", question)
        .replace("{citations_block}", citations_block)
        .replace("{context_block}", context_block)
    )
